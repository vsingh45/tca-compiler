def generate_all_tasks() -> list[dict]:
    """Generate all 200 tasks with stable IDs."""
    all_tasks = []
    task_num = 0

    category_map = {
        "Billing": BILLING_TASKS,
        "SAM": SAM_TASKS,
        "IAM": IAM_TASKS,
        "CrossDomain": CROSS_TASKS,
        "Policy": POLICY_TASKS,
    }

    for category, depth_map in category_map.items():
        for depth, task_list in sorted(depth_map.items()):
            for task in task_list:
                task_num += 1
                all_tasks.append({
                    "task_id": f"T{task_num:03d}",
                    "category": category,
                    "depth": depth,
                    "query": task["query"],
                    "workflow": task["workflow"],
                    "required_topics": task["required_topics"],
                    "db": task["db"],
                    "seed": SEED,
                })

    return all_tasks


def main() -> None:
    tasks = generate_all_tasks()

    # Write all tasks to a single JSON file
    output_file = OUTPUT_DIR / "tasks.json"
    with open(output_file, "w") as f:
        json.dump(tasks, f, indent=2)

    print(f"Generated {len(tasks)} tasks → {output_file}")

    # Stats
    by_category: dict[str, int] = {}
    by_depth: dict[int, int] = {}
    for t in tasks:
        by_category[t["category"]] = by_category.get(t["category"], 0) + 1
        by_depth[t["depth"]] = by_depth.get(t["depth"], 0) + 1

    print("\nBy category:")
    for cat, count in sorted(by_category.items()):
        print(f"  {cat}: {count}")

    print("\nBy depth:")
    for depth, count in sorted(by_depth.items()):
        print(f"  depth {depth}: {count}")


